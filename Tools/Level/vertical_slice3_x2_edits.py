# globals: blocks, objects, points, put, clear, column_clear, fill, carve, obj, OrderedDict

def crate(oid, x, y, z, yaw, height=2):
    o = next((o for o in objects if o['id'] == oid), None)
    if o is None:
        o = OrderedDict(id=oid, kind='CrateStack')
        objects.append(o)
    o['cell'] = f'{x},{y},{z}'
    if yaw:
        o['yaw'] = yaw
    else:
        o.pop('yaw', None)
    o['height'] = height

# ---------------------------------------------------------------- мост и пропасть
# Пропасть на всю длину моста (8 клеток): ближний берег (арена) z ≥ 40, дальний (старт) z ≤ 31.
carve(52, 79, 32, 39)
b = obj('drawbridge_1')
b['cell'] = '60,1,39'          # ближний край опущенной створки у берега арены, длина по −Z до z=32
b['yaw'] = 90
b['height'] = 4
# Дальний берег — ворота: причал 3×4 ровно по ширине моста между стенами (верх 4, на 3 выше настила),
# чтобы с конца ближней створки нельзя было перепрыгнуть мимо поднятой створки. Клетка z=31 у стен — пропасть,
# в ней видны шестерни шарнира; столбы дальней рамы уходят в стены.
fill(56, 59, 28, 30, 4)
fill(63, 65, 28, 30, 4)
carve(52, 59, 31, 31)   # западнее ворот край берега тоже отодвинут, чтобы с угла ближней створки не допрыгнуть
carve(63, 65, 31, 31)
for x in range(60, 63):       # причал
    for z in range(28, 32):
        column_clear(x, z)
        put(x, -1, z); put(x, 0, z)

# ---------------------------------------------------------------- ящики (стопка 2×1, ломает меч)
# Коридор на запад от стартовой зоны (был 2 клетки, стал 4): две стопки поперёк.
crate('cratestack_1', 38, 1, 26, 270)
crate('cratestack_1b', 38, 1, 28, 270)
# Проход с юга на плато (x 18..21).
crate('cratestack_2', 18, 2, 36, 0)
crate('cratestack_2b', 20, 2, 36, 0)
# Срезка к костру: ящики перед площадкой у крутого слопа.
crate('cratestack_3', 40, 2, 38, 270)
crate('cratestack_3b', 40, 2, 40, 270)
# Закуток с сундуком на западе: вход выровнен в прямой проём 4 клетки (выступ плато залит стеной), две стопки поперёк.
fill(14, 15, 46, 47, 4)
crate('cratestack_5', 15, 2, 48, 270)
crate('cratestack_4', 15, 2, 50, 270)
# Коридор к сундуку у комнаты с дробовиком (2 клетки шириной): одна стопка поперёк.
crate('cratestack_6', 27, 2, 64, 270)

# ---------------------------------------------------------------- дверь на ключ
# Проём стал 2 клетки, дверь — 1: вторую клетку проёма закладываем стеной до верха соседних (6).
fill(26, 27, 77, 77, 6)
obj('keydoor_1')['cell'] = '27,4,76'
# Ключ от двери снова у элиты в северо-западном зале (связь пропала в рабочей копии).
obj('enemyspawn_9')['key'] = 'keydoor_1'


# Прыжок из коридора на уступ арены был через 2 клетки (идёшь шагом — допрыгиваешь); после ×2 стал 4.
# Уступ продлён на 2 клетки к коридору — снова 2 клетки.
fill(48, 49, 56, 57, 2)

# Расстояния между врагами удвоились — радиусы агро ×1.5, чтобы группы (четвёрка на арене) по-прежнему поднимались вместе.
for o in objects:
    if o.get('kind') == 'EnemySpawn' and 'aggroRadius' in o:
        o['aggroRadius'] = round(o['aggroRadius'] * 1.5, 2)
