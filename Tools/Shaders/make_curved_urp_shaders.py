"""Builds ColorsAction/Lit and ColorsAction/Unlit from the project's URP Lit/Unlit shaders.

The copies are identical to URP except that every pass that matters on screen (forward, gbuffer, shadow
caster, depth, depth-normals) runs its vertices through CurvedWorldBendOS first (Assets/Game/Art/Shaders/
CurvedWorld.hlsl). Material properties and the inspector stay the same as URP's, so a material just switches
shader. Re-run after a URP upgrade:  python Tools/Shaders/make_curved_urp_shaders.py
"""
import glob
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "Assets", "Game", "Art", "Shaders")

# vertex entry -> field with the object-space position in its Attributes
FIELDS = {
    "LitPassVertex": "positionOS",
    "LitGBufferPassVertex": "positionOS",
    "UnlitPassVertex": "positionOS",
    "ShadowPassVertex": "positionOS",
    "DepthOnlyVertex": "position",
    "DepthNormalsVertex": "positionOS",
}

WRAPPER = """
            // ColorsAction: искривление мира (см. CurvedWorld.hlsl)
            #include "Assets/Game/Art/Shaders/CurvedWorld.hlsl"
            Varyings Curved{entry}(Attributes input)
            {{
                UNITY_SETUP_INSTANCE_ID(input);
                input.{field}.xyz = CurvedWorldBendOS(input.{field}.xyz);
                return {entry}(input);
            }}
"""


def convert(src_path, name, dst_path):
    text = open(src_path, encoding="utf-8").read()
    text = re.sub(r'Shader\s+"[^"]+"', f'Shader "{name}"', text, count=1)
    # Split by HLSL blocks and patch the ones whose vertex entry we know.
    parts = re.split(r"(HLSLPROGRAM.*?ENDHLSL)", text, flags=re.S)
    patched = 0
    for i, part in enumerate(parts):
        if not part.startswith("HLSLPROGRAM"):
            continue
        m = re.search(r"#pragma vertex (\w+)", part)
        if not m or m.group(1) not in FIELDS:
            continue
        entry = m.group(1)
        part = part.replace(m.group(0), f"#pragma vertex Curved{entry}", 1)
        part = part[: -len("ENDHLSL")].rstrip(" ") + WRAPPER.format(entry=entry, field=FIELDS[entry]).lstrip("\n") + "            ENDHLSL"
        parts[i] = part
        patched += 1
    header = (
        f"// GENERATED by Tools/Shaders/make_curved_urp_shaders.py from {os.path.basename(src_path)} (URP). Do not edit by hand.\n"
        f"// URP shader + искривление мира (CurvedWorld.hlsl) в проходах forward/gbuffer/shadow/depth.\n"
    )
    open(dst_path, "w", encoding="utf-8", newline="\n").write(header + "".join(parts))
    print(f"{dst_path}: {patched} passes patched")


def main():
    urp = sorted(glob.glob(os.path.join(ROOT, "Library", "PackageCache", "com.unity.render-pipelines.universal@*", "Shaders")))
    if not urp:
        sys.exit("URP package not found in Library/PackageCache")
    shaders = urp[-1]
    convert(os.path.join(shaders, "Lit.shader"), "ColorsAction/Lit", os.path.join(OUT, "CurvedLit.shader"))
    convert(os.path.join(shaders, "Unlit.shader"), "ColorsAction/Unlit", os.path.join(OUT, "CurvedUnlit.shader"))


if __name__ == "__main__":
    main()
